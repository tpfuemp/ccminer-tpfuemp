	const uint32_t g9 = wpx4_lop3<0x74>(x1, x2, x3);
	const uint32_t g10 = wpx4_lop3<0x71>(x1, x2, x3);
	const uint32_t g11 = wpx4_lop3<0xD8>(g9, g10, x0);
	y0 = g2;
	y1 = g5;
	y2 = g8;
	y3 = g11;
}

#define WPX4_SWAP(x, y, m, n) do { const uint32_t t_ = ((x) ^ ((y) << (n))) & (m); (x) ^= t_; (y) ^= t_ >> (n); } while (0)

/* 8 words x 4 bytes -> 8 bit planes: swaps index bits (word k) <-> (bit b). An involution. */
__device__ __forceinline__
void whirlpool512_x4_transpose(uint32_t *d)
{
	WPX4_SWAP(d[0], d[1], 0xaaaaaaaau, 1); WPX4_SWAP(d[2], d[3], 0xaaaaaaaau, 1);
	WPX4_SWAP(d[4], d[5], 0xaaaaaaaau, 1); WPX4_SWAP(d[6], d[7], 0xaaaaaaaau, 1);
	WPX4_SWAP(d[0], d[2], 0xccccccccu, 2); WPX4_SWAP(d[1], d[3], 0xccccccccu, 2);
	WPX4_SWAP(d[4], d[6], 0xccccccccu, 2); WPX4_SWAP(d[5], d[7], 0xccccccccu, 2);
	WPX4_SWAP(d[0], d[4], 0xf0f0f0f0u, 4); WPX4_SWAP(d[1], d[5], 0xf0f0f0f0u, 4);
	WPX4_SWAP(d[2], d[6], 0xf0f0f0f0u, 4); WPX4_SWAP(d[3], d[7], 0xf0f0f0f0u, 4);
}

/* S-box from its 4-bit parts: u = E(hi), l = E^-1(lo), r = R(u ^ l), out = E(u ^ r), E^-1(l ^ r) */
__device__ __forceinline__
void whirlpool512_x4_sbox(uint32_t *q)
{
	uint32_t u0, u1, u2, u3, l0, l1, l2, l3, r0, r1, r2, r3;
	wpx4_e(q[4], q[5], q[6], q[7], u0, u1, u2, u3);
	wpx4_ei(q[0], q[1], q[2], q[3], l0, l1, l2, l3);
	wpx4_r(u0 ^ l0, u1 ^ l1, u2 ^ l2, u3 ^ l3, r0, r1, r2, r3);
	wpx4_e(u0 ^ r0, u1 ^ r1, u2 ^ r2, u3 ^ r3, q[4], q[5], q[6], q[7]);
	wpx4_ei(l0 ^ r0, l1 ^ r1, l2 ^ r2, l3 ^ r3, q[0], q[1], q[2], q[3]);
}

/* GF(2^8) doubling, poly 0x11d, on 8 bit planes */
__device__ __forceinline__
void whirlpool512_x4_mul2(const uint32_t *x, uint32_t *o)
{
	o[0] = x[7]; o[1] = x[0]; o[2] = x[1] ^ x[7]; o[3] = x[2] ^ x[7];
	o[4] = x[3] ^ x[7]; o[5] = x[4]; o[6] = x[5]; o[7] = x[6];
}

/* SubBytes, ShiftColumns (column j rotated by 4j), MixRows; the caller adds the round key.
 * W1 = false: Whirlpool, circ(1,1,4,1,8,5,2,9); W1 = true: whirlpool1, circ(1,1,3,1,5,8,9,5). */
template <bool W1> __device__ __forceinline__
void whirlpool512_x4_round(uint32_t (&s)[8][8])
{
	#pragma unroll
	for (int c = 0; c < 8; c++) whirlpool512_x4_sbox(s[c]);
	#pragma unroll
	for (int c = 1; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[c][b] = __funnelshift_l(s[c][b], s[c][b], 4 * c);
	uint32_t B[8][8];
	if (!W1) {
		/* b_j = X1_j + 2(A_{j-6} + 2(U_{j+2} + 2U_j)), U_j = A_{j-4} + A_{j-7} */
		uint32_t U[8][8];
		#pragma unroll
		for (int j = 0; j < 8; j++)
			#pragma unroll
			for (int b = 0; b < 8; b++) U[j][b] = s[(j + 4) & 7][b] ^ s[(j + 1) & 7][b];
		#pragma unroll
		for (int j = 0; j < 8; j++) {
			uint32_t v[8], w[8], z[8];
			whirlpool512_x4_mul2(U[j], v);
			#pragma unroll
			for (int b = 0; b < 8; b++) v[b] ^= U[(j + 2) & 7][b];
			whirlpool512_x4_mul2(v, w);
			#pragma unroll
			for (int b = 0; b < 8; b++) w[b] ^= s[(j + 2) & 7][b];
			whirlpool512_x4_mul2(w, z);
			#pragma unroll
			for (int b = 0; b < 8; b++)
				B[j][b] = z[b] ^ s[j][b] ^ s[(j + 7) & 7][b] ^ s[(j + 5) & 7][b] ^ s[(j + 3) & 7][b] ^ s[(j + 1) & 7][b];
		}
	} else {
		/* b_j = T + A_{j-5} + 2(A_{j-2} + 2(A_{j-4} + A_{j-7} + 2(A_{j-5} + A_{j-6}))), T = sum of all */
		uint32_t T[8];
		#pragma unroll
		for (int b = 0; b < 8; b++)
			T[b] = s[0][b] ^ s[1][b] ^ s[2][b] ^ s[3][b] ^ s[4][b] ^ s[5][b] ^ s[6][b] ^ s[7][b];
		#pragma unroll
		for (int j = 0; j < 8; j++) {
			uint32_t v[8], w[8], x[8], z[8];
			#pragma unroll
			for (int b = 0; b < 8; b++) v[b] = s[(j + 3) & 7][b] ^ s[(j + 2) & 7][b];
			whirlpool512_x4_mul2(v, w);
			#pragma unroll
			for (int b = 0; b < 8; b++) w[b] ^= s[(j + 4) & 7][b] ^ s[(j + 1) & 7][b];
			whirlpool512_x4_mul2(w, x);
			#pragma unroll
			for (int b = 0; b < 8; b++) x[b] ^= s[(j + 6) & 7][b];
			whirlpool512_x4_mul2(x, z);
			#pragma unroll
			for (int b = 0; b < 8; b++) B[j][b] = z[b] ^ T[b] ^ s[(j + 3) & 7][b];
		}
	}
	#pragma unroll
	for (int j = 0; j < 8; j++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[j][b] = B[j][b];
}

/* one 64-byte message -> its digest, in planes and in place; k1 = block-1 keys (zero IV) */
template <bool W1> __device__ __forceinline__
void whirlpool512_x4_compress64(uint32_t (&s)[8][8], const uint32_t (&k1)[10][64], uint32_t *st, const uint32_t stride)
{
	#define ST(c, b) st[((c) * 8 + (b)) * stride]
	#pragma unroll
	for (int c = 0; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) ST(c, b) = s[c][b];
	#pragma unroll 1
	for (int r = 0; r < 10; r++) {
		whirlpool512_x4_round<W1>(s);
		#pragma unroll
		for (int c = 0; c < 8; c++)
			#pragma unroll
			for (int b = 0; b < 8; b++) s[c][b] ^= k1[r][c * 8 + b];
	}
	/* block 2: key = H1 = W ^ m, message = the constant padding block */
	uint32_t K[8][8];
	#pragma unroll
	for (int c = 0; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) {
			const uint32_t h1 = s[c][b] ^ ST(c, b);
			ST(c, b) = h1; K[c][b] = h1; s[c][b] = h1 ^ c_wpx4_pad[c * 8 + b];
		}
	#pragma unroll 1
	for (int r = 0; r < 10; r++) {
		whirlpool512_x4_round<W1>(K);
		#pragma unroll
		for (int c = 0; c < 8; c++)
			#pragma unroll
			for (int b = 0; b < 8; b++) K[c][b] ^= c_wpx4_rc[r][c * 8 + b];
		whirlpool512_x4_round<W1>(s);
		#pragma unroll
		for (int c = 0; c < 8; c++)
			#pragma unroll
			for (int b = 0; b < 8; b++) s[c][b] ^= K[c][b];
	}
	#pragma unroll
	for (int c = 0; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[c][b] ^= ST(c, b) ^ c_wpx4_pad[c * 8 + b];
	#undef ST
}

/* four 64-byte messages (16 LE words each) -> planes */
__device__ __forceinline__
void whirlpool512_x4_load64(const uint32_t (&in)[4][16], uint32_t (&s)[8][8])
{
	/* column c: W[k] byte n = byte(row 2n + (k>>2), col c) of hash k&3 */
	#pragma unroll
	for (int c = 0; c < 8; c++) {
		#pragma unroll
		for (int k = 0; k < 8; k++) {
			const int h = k & 3, kb = k >> 2, cw = c >> 2, cb = c & 3;
			const uint32_t sel = 0x4400 + cb + ((4 + cb) << 4);
			const uint32_t lo = __byte_perm(in[h][2 * kb + cw], in[h][2 * (2 + kb) + cw], sel);
			const uint32_t hi = __byte_perm(in[h][2 * (4 + kb) + cw], in[h][2 * (6 + kb) + cw], sel);
			s[c][k] = __byte_perm(lo, hi, 0x5410);
		}
		whirlpool512_x4_transpose(s[c]);
	}
}

/* un-transposed planes (s[c] = W_c) -> digests of hashes h < n at the 64-byte slots g[i0 + h];
 * digest word w of hash h: row r = w>>1, cols 4(w&1)..+3 -> W_c[4(r&1) + h] byte (r>>1) */
__device__ __forceinline__
void whirlpool512_x4_store(const uint32_t (&s)[8][8], uint32_t *g, const uint32_t i0, const int n)
{
	#pragma unroll
	for (int h = 0; h < 4; h++) {
		if (h >= n) break;
		uint32_t ow[16];
		#pragma unroll
		for (int w = 0; w < 16; w++) {
			const int r = w >> 1, c0 = 4 * (w & 1), k = 4 * (r & 1) + h, nb = r >> 1;
			const uint32_t sel = 0x4400 + nb + ((4 + nb) << 4);
			const uint32_t lo = __byte_perm(s[c0][k], s[c0 + 1][k], sel);
			const uint32_t hi = __byte_perm(s[c0 + 2][k], s[c0 + 3][k], sel);
			ow[w] = __byte_perm(lo, hi, 0x5410);
		}
		uint4 *o = (uint4*) &g[(size_t)(i0 + h) << 4];
		#pragma unroll
		for (int k = 0; k < 4; k++) o[k] = make_uint4(ow[4*k], ow[4*k+1], ow[4*k+2], ow[4*k+3]);
	}
}

/* host: one 64-byte state (row-major) broadcast to the planes of all four hashes */
static inline void whirlpool512_x4_bcast(const uint8_t *m, uint32_t *planes)
{
	for (int c = 0; c < 8; c++)
		for (int b = 0; b < 8; b++) {
			uint32_t w = 0;
			for (int row = 0; row < 8; row++)
				if ((m[8 * row + c] >> b) & 1) w |= 0xFu << (4 * row);
			planes[c * 8 + b] = w;
		}
}

/* 80-byte header, second block: nonce bits of hashes n0 .. n0+3 (bytes 12..15 = row 1, cols 4..7,
 * big-endian), to XOR into columns 4..7 */
__device__ __forceinline__
void whirlpool512_x4_nonce80(const uint32_t n0, uint32_t (&nz)[4][8])
{
	#pragma unroll
	for (int k = 0; k < 4; k++)
		#pragma unroll
		for (int b = 0; b < 8; b++) {
			uint32_t w = 0;
			#pragma unroll
			for (int h = 0; h < 4; h++)
				w |= (((n0 + h) >> (8 * (3 - k) + b)) & 1u) << (4 + h);
			nz[k][b] = w;
		}
}

/* host: one round on 64-bit rows with table T (plain_T0 or old1_T0): out = theta(pi(gamma(in))) ^ c */
static inline void whirlpool512_x4_host_round(const uint64_t *T, const uint64_t *in, uint64_t *out, const uint64_t *c)
{
	for (int i = 0; i < 8; i++) {
		uint64_t v = c[i];
		for (int k = 0; k < 8; k++) {
			const uint64_t t = T[(in[(i - k) & 7] >> (8 * k)) & 0xFF];
			v ^= k ? ((t << (8 * k)) | (t >> (64 - 8 * k))) : t;
		}
		out[i] = v;
	}
}

/* host, per job: the second block of an 80-byte header with the nonce zeroed. h1 = the first
 * block's chaining value; planes[0] = H1 ^ block 2, planes[1..10] = the block-2 round keys. */
static inline void whirlpool512_x4_prepare80(const uint64_t *T, const uint64_t *RC, const uint64_t *h1,
	const void *hdr80, uint32_t (*planes)[64])
{
	uint64_t m2[8] = { 0 }, st0[8], key[8], tmp[8], rc[8] = { 0 };
	memcpy(m2, (const uint8_t*) hdr80 + 64, 12);
	m2[2] = 0x80;                                            /* padding */
	m2[7] = 0x8002000000000000ULL;                           /* length: 640 bits, big-endian */
	for (int i = 0; i < 8; i++) { st0[i] = m2[i] ^ h1[i]; key[i] = h1[i]; }
	whirlpool512_x4_bcast((const uint8_t*) st0, planes[0]);
	for (int r = 0; r < 10; r++) {
		rc[0] = RC[r];
		whirlpool512_x4_host_round(T, key, tmp, rc);
		memcpy(key, tmp, sizeof(key));
		whirlpool512_x4_bcast((const uint8_t*) key, planes[1 + r]);
	}
}

/* 80-byte header -> digest planes of hashes n0 .. n0+3, from the prepare80 constants */
template <bool W1> __device__ __forceinline__
void whirlpool512_x4_hash80(const uint32_t (&st0)[64], const uint32_t (&key)[10][64], const uint32_t n0,
	uint32_t (&s)[8][8])
{
	uint32_t nz[4][8];
	whirlpool512_x4_nonce80(n0, nz);
	#pragma unroll
	for (int c = 0; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[c][b] = st0[c * 8 + b] ^ (c >= 4 ? nz[c - 4][b] : 0u);
	#pragma unroll 1
	for (int r = 0; r < 10; r++) {
		whirlpool512_x4_round<W1>(s);
		#pragma unroll
		for (int c = 0; c < 8; c++)
			#pragma unroll
			for (int b = 0; b < 8; b++) s[c][b] ^= key[r][c * 8 + b];
	}
	/* H = W ^ H1 ^ block 2 = W ^ the initial state */
	whirlpool512_x4_nonce80(n0, nz);
	#pragma unroll
	for (int c = 0; c < 8; c++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[c][b] ^= st0[c * 8 + b] ^ (c >= 4 ? nz[c - 4][b] : 0u);
}

/* Whirlpool of four 64-byte messages in[h] (16 LE words); digest h is stored to the 64-byte
 * slot g[i0 + h] for h < n. st: this thread's 64-word stash, word k at st[k * stride]. */
__device__ __forceinline__
void whirlpool512_x4_hash_64(const uint32_t (&in)[4][16], uint32_t *st, const uint32_t stride,
	uint32_t *g, const uint32_t i0, const int n)
{
	uint32_t s[8][8];
	whirlpool512_x4_load64(in, s);
	whirlpool512_x4_compress64<false>(s, c_wpx4_k1, st, stride);
	#pragma unroll
	for (int c = 0; c < 8; c++) whirlpool512_x4_transpose(s[c]);
	whirlpool512_x4_store(s, g, i0, n);
}

