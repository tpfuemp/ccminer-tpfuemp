__device__ __forceinline__
void groestl512_x2_round(uint32_t (&s)[8][8], const uint32_t r, const bool q, const uint32_t (&rot)[8])
{
	if (q) {
		#pragma unroll
		for (int i = 0; i < 8; i++)
			#pragma unroll
			for (int b = 0; b < 8; b++) s[i][b] = ~s[i][b];
		#pragma unroll
		for (int b = 0; b < 4; b++) s[7][b] ^= 0u - ((r >> b) & 1u);
		s[7][4] ^= 0xCCCCCCCCu; s[7][5] ^= 0xF0F0F0F0u; s[7][6] ^= 0xFF00FF00u; s[7][7] ^= 0xFFFF0000u;
	} else {
		#pragma unroll
		for (int b = 0; b < 4; b++) s[0][b] ^= 0u - ((r >> b) & 1u);
		s[0][4] ^= 0xCCCCCCCCu; s[0][5] ^= 0xF0F0F0F0u; s[0][6] ^= 0xFF00FF00u; s[0][7] ^= 0xFFFF0000u;
	}
	/* ShiftBytes before SubBytes (they commute) */
	#pragma unroll
	for (int i = 0; i < 8; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] = __funnelshift_r(s[i][b], s[i][b], rot[i]);
	#pragma unroll
	for (int i = 0; i < 8; i++) groestl512_x2_sbox(s[i]);
	groestl512_x2_mix(s);
}

__device__ __forceinline__
void groestl512_x2_perm(uint32_t (&s)[8][8], const bool q)
{
	/* ShiftBytes sigma, P: 0 1 2 3 4 5 6 11, Q: 1 3 5 11 0 2 4 6 (columns) -> rotate 2*sigma bits */
	uint32_t rot[8];
	rot[0] = q ? 2 : 0;  rot[1] = q ? 6 : 2;  rot[2] = q ? 10 : 4; rot[3] = q ? 22 : 6;
	rot[4] = q ? 0 : 8;  rot[5] = q ? 4 : 10; rot[6] = q ? 8 : 12; rot[7] = q ? 12 : 22;
	#pragma unroll 1
	for (uint32_t r = 0; r < 14; r++) groestl512_x2_round(s, r, q, rot);
}

/* ---- message loaders: planes s[8][8] of the padded 1024-bit block, both hashes ---- */

/* two 64-byte messages (16 LE words each): row r, W[k] byte n = byte(row r, col 4n + (k>>1))
 * of hash k&1; cols 8..15 are padding (0x80 at col 8 row 0, block count 1 at col 15 row 7) */
__device__ __forceinline__
void groestl512_x2_load64(const uint32_t (&in)[2][16], uint32_t (&s)[8][8])
{
	#pragma unroll
	for (int r = 0; r < 8; r++) {
		#pragma unroll
		for (int k = 0; k < 8; k++) {
			const int h = k & 1, cc = k >> 1, rw = r >> 2, rb = r & 3;
			s[r][k] = __byte_perm(in[h][2 * cc + rw], in[h][8 + 2 * cc + rw], 0x4400 + rb + ((4 + rb) << 4)) & 0xFFFFu;
		}
		if (r == 0) { s[0][0] |= 0x00800000u; s[0][1] |= 0x00800000u; }      /* col 8 row 0 = 0x80 */
		if (r == 7) { s[7][6] |= 0x01000000u; s[7][7] |= 0x01000000u; }      /* col 15 row 7 = 0x01 */
		groestl512_x2_transpose(s[r]);
	}
}

/* two 80-byte headers (20 LE words each, typically equal but for word 19 = the nonce):
 * cols 0..9 from the header, 0x80 at col 10 row 0, block count 1 at col 15 row 7 */
__device__ __forceinline__
void groestl512_x2_load80(const uint32_t (&m)[2][20], uint32_t (&s)[8][8])
{
	#pragma unroll
	for (int r = 0; r < 8; r++) {
		#pragma unroll
		for (int k = 0; k < 8; k++) {
			const int h = k & 1, cc = k >> 1, rw = r >> 2, rb = r & 3;
			uint32_t v = __byte_perm(m[h][2 * cc + rw], m[h][8 + 2 * cc + rw], 0x4400 + rb + ((4 + rb) << 4)) & 0xFFFFu;
			if (cc < 2)                                                        /* cols 8, 9 */
				v |= __byte_perm(m[h][16 + 2 * cc + rw], 0, 0x4044 + (rb << 8)) & 0x00FF0000u;
			s[r][k] = v;
		}
		if (r == 0) { s[0][4] |= 0x00800000u; s[0][5] |= 0x00800000u; }      /* col 10 row 0 = 0x80 */
		if (r == 7) { s[7][6] |= 0x01000000u; s[7][7] |= 0x01000000u; }      /* col 15 row 7 = 0x01 */
		groestl512_x2_transpose(s[r]);
	}
}

/* one compression from IV, in place: s = P(H) ^ H with H = P(m ^ IV) ^ Q(m) ^ IV (digest =
 * cols 8..15). stride = blockDim.x for a conflict-free [64][blockDim] shared stash. */
__device__ __forceinline__
void groestl512_x2_compress(uint32_t (&s)[8][8], uint32_t *st, const uint32_t stride)
{
	/* 3 permutations sharing one body: P(m ^ IV), Q(m), P(H) */
	#define ST(i, b) st[((i) * 8 + (b)) * stride]
	#pragma unroll 1
	for (int p = 0; p < 3; p++) {
		if (p == 0) {
			#pragma unroll
			for (int i = 0; i < 8; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) ST(i, b) = s[i][b];
			s[6][1] ^= 0xC0000000u;                                           /* IV: col 15 row 6 = 0x02 */
		} else if (p == 1) {
			#pragma unroll
			for (int i = 0; i < 8; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) { const uint32_t v = ST(i, b); ST(i, b) = s[i][b]; s[i][b] = v; }
		} else {
			#pragma unroll
			for (int i = 0; i < 8; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) { s[i][b] ^= ST(i, b); ST(i, b) = s[i][b] ^ ((i == 6 && b == 1) ? 0xC0000000u : 0u); }
			s[6][1] ^= 0xC0000000u;
		}
		groestl512_x2_perm(s, p == 1);
	}
	#pragma unroll
	for (int i = 0; i < 8; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] ^= ST(i, b);
	#undef ST
}

/* the 64-byte digest (cols 8..15) as the padded message block of a chained Groestl-512:
 * cols move 8 -> 0 (a 16-bit rotate of every plane), then the load64 padding bits */
__device__ __forceinline__
void groestl512_x2_digest_to_msg64(uint32_t (&s)[8][8])
{
	#pragma unroll
	for (int i = 0; i < 8; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] >>= 16;
	s[0][7] |= 0x00030000u;                                                   /* col 8 row 0 = 0x80 */
	s[7][0] |= 0xC0000000u;                                                   /* col 15 row 7 = 0x01 */
}

/* digest word w of hash h: col c = 8 + (w>>1), rows 4(w&1)+j -> W_row[2(c&3)+h] byte (c>>2).
 * Transposes s in place (s is consumed). */
__device__ __forceinline__
void groestl512_x2_store(uint32_t (&s)[8][8], uint32_t (&out)[2][16])
{
	#pragma unroll
	for (int i = 0; i < 8; i++) groestl512_x2_transpose(s[i]);
	#pragma unroll
	for (int h = 0; h < 2; h++)
		#pragma unroll
		for (int w = 0; w < 16; w++) {
			const int c = 8 + (w >> 1), k = 2 * (c & 3) + h, n = c >> 2, r0 = 4 * (w & 1);
			const uint32_t sel = n + ((4 + n) << 4);                              /* byte n of a -> 0, of b -> 1 */
			const uint32_t lo = __byte_perm(s[r0][k], s[r0 + 1][k], sel);
			const uint32_t hi = __byte_perm(s[r0 + 2][k], s[r0 + 3][k], sel);
			out[h][w] = __byte_perm(lo, hi, 0x5410);
		}
}

/* Groestl-512 of two 64-byte messages in[0], in[1], digests written back into in[] */
__device__ __forceinline__
void groestl512_x2_hash_64(uint32_t (&in)[2][16], uint32_t *st, const uint32_t stride)
{
	uint32_t s[8][8];
	groestl512_x2_load64(in, s);
	groestl512_x2_compress(s, st, stride);
	groestl512_x2_store(s, in);
}

/* ---- the same two hashes on a thread pair (lanes 2p, 2p+1) ----
 * Lane q = threadIdx.x & 1 holds rows 4q..4q+3 (s[4][8]); MixBytes gets the partner's rows by
 * __shfl_xor(1) and, being circulant, runs on rows relative to the lane's own (A_k = row (k + 4q) & 7).
 * Every lane of the warp must call these (full-mask shuffles). */

__device__ __forceinline__
void groestl512_pair_mix(uint32_t (&s)[4][8])
{
	uint32_t A[8][8];
	#pragma unroll
	for (int i = 0; i < 4; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) {
			A[i][b] = s[i][b];
			A[4 + i][b] = __shfl_xor_sync(0xffffffffu, s[i][b], 1);
		}
	/* outputs 0..3 need w_3..w_6 (from x_3..x_6) and all eight y */
	uint32_t y[8][8], w[4][8];
	#pragma unroll
	for (int b = 0; b < 8; b++) {
		uint32_t t[8];
		#pragma unroll
		for (int i = 0; i < 8; i++) t[i] = A[i][b] ^ A[(i + 1) & 7][b];
		#pragma unroll
		for (int i = 0; i < 8; i++) y[i][b] = t[i] ^ t[(i + 2) & 7] ^ A[(i + 6) & 7][b];
		#pragma unroll
		for (int j = 0; j < 4; j++) w[j][b] = t[3 + j] ^ t[(3 + j + 3) & 7];
	}
	#pragma unroll
	for (int j = 0; j < 4; j++) {
		uint32_t m[8]; groestl512_x2_mul2(w[j], m);
		#pragma unroll
		for (int b = 0; b < 8; b++) w[j][b] = m[b] ^ y[(3 + j + 4) & 7][b];
	}
	#pragma unroll
	for (int i = 0; i < 4; i++) {
		uint32_t m[8]; groestl512_x2_mul2(w[i], m);
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] = m[b] ^ y[(i + 4) & 7][b];
	}
}

/* mq0 = all ones on lane 0 (owns global row 0), mq1 = all ones on lane 1 (owns global row 7) */
__device__ __forceinline__
void groestl512_pair_round(uint32_t (&s)[4][8], const uint32_t r, const bool q, const uint32_t mq0,
	const uint32_t mq1, const uint32_t (&rot)[4])
{
	if (q) {
		#pragma unroll
		for (int i = 0; i < 4; i++)
			#pragma unroll
			for (int b = 0; b < 8; b++) s[i][b] = ~s[i][b];
		#pragma unroll
		for (int b = 0; b < 4; b++) s[3][b] ^= mq1 & (0u - ((r >> b) & 1u));
		s[3][4] ^= mq1 & 0xCCCCCCCCu; s[3][5] ^= mq1 & 0xF0F0F0F0u; s[3][6] ^= mq1 & 0xFF00FF00u; s[3][7] ^= mq1 & 0xFFFF0000u;
	} else {
		#pragma unroll
		for (int b = 0; b < 4; b++) s[0][b] ^= mq0 & (0u - ((r >> b) & 1u));
		s[0][4] ^= mq0 & 0xCCCCCCCCu; s[0][5] ^= mq0 & 0xF0F0F0F0u; s[0][6] ^= mq0 & 0xFF00FF00u; s[0][7] ^= mq0 & 0xFFFF0000u;
	}
	#pragma unroll
	for (int i = 0; i < 4; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] = __funnelshift_r(s[i][b], s[i][b], rot[i]);
	#pragma unroll
	for (int i = 0; i < 4; i++) groestl512_x2_sbox(s[i]);
	groestl512_pair_mix(s);
}

__device__ __forceinline__
void groestl512_pair_perm(uint32_t (&s)[4][8], const bool q, const uint32_t lane)
{
	const uint32_t mq1 = 0u - lane, mq0 = ~mq1;
	uint32_t rot[4];
	if (q) { rot[0] = lane ? 0 : 2;  rot[1] = lane ? 4 : 6;  rot[2] = lane ? 8 : 10;  rot[3] = lane ? 12 : 22; }
	else   { rot[0] = lane ? 8 : 0;  rot[1] = lane ? 10 : 2; rot[2] = lane ? 12 : 4;  rot[3] = lane ? 22 : 6; }
	#pragma unroll 1
	for (uint32_t r = 0; r < 14; r++) groestl512_pair_round(s, r, q, mq0, mq1, rot);
}

/* this lane's rows of two 64-byte messages; inq[h][n] = message word 2n + lane of hash h */
__device__ __forceinline__
void groestl512_pair_load64(const uint32_t (&inq)[2][8], uint32_t (&s)[4][8], const uint32_t lane)
{
	const uint32_t mq1 = 0u - lane, mq0 = ~mq1;
	#pragma unroll
	for (int i = 0; i < 4; i++) {
		#pragma unroll
		for (int k = 0; k < 8; k++) {
			const int h = k & 1, cc = k >> 1;
			s[i][k] = __byte_perm(inq[h][cc], inq[h][4 + cc], 0x4400 + i + ((4 + i) << 4)) & 0xFFFFu;
		}
		if (i == 0) { s[0][0] |= mq0 & 0x00800000u; s[0][1] |= mq0 & 0x00800000u; }  /* col 8 row 0 = 0x80 */
		if (i == 3) { s[3][6] |= mq1 & 0x01000000u; s[3][7] |= mq1 & 0x01000000u; }  /* col 15 row 7 = 0x01 */
		groestl512_x2_transpose(s[i]);
	}
}

/* as groestl512_x2_compress, 32-word stash per lane */
__device__ __forceinline__
void groestl512_pair_compress(uint32_t (&s)[4][8], uint32_t *st, const uint32_t stride, const uint32_t lane)
{
	const uint32_t mq1 = 0u - lane;                         /* IV: global row 6 = row 2 of lane 1 */
	#define ST(i, b) st[((i) * 8 + (b)) * stride]
	#pragma unroll 1
	for (int p = 0; p < 3; p++) {
		if (p == 0) {
			#pragma unroll
			for (int i = 0; i < 4; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) ST(i, b) = s[i][b];
			s[2][1] ^= mq1 & 0xC0000000u;
		} else if (p == 1) {
			#pragma unroll
			for (int i = 0; i < 4; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) { const uint32_t v = ST(i, b); ST(i, b) = s[i][b]; s[i][b] = v; }
		} else {
			#pragma unroll
			for (int i = 0; i < 4; i++)
				#pragma unroll
				for (int b = 0; b < 8; b++) { s[i][b] ^= ST(i, b); ST(i, b) = s[i][b] ^ ((i == 2 && b == 1) ? (mq1 & 0xC0000000u) : 0u); }
			s[2][1] ^= mq1 & 0xC0000000u;
		}
		groestl512_pair_perm(s, p == 1, lane);
	}
	#pragma unroll
	for (int i = 0; i < 4; i++)
		#pragma unroll
		for (int b = 0; b < 8; b++) s[i][b] ^= ST(i, b);
	#undef ST
}

/* digest words 2n + lane (n = 0..7) of both hashes */
__device__ __forceinline__
void groestl512_pair_store(uint32_t (&s)[4][8], uint32_t (&outq)[2][8])
{
	#pragma unroll
	for (int i = 0; i < 4; i++) groestl512_x2_transpose(s[i]);
	#pragma unroll
	for (int h = 0; h < 2; h++)
		#pragma unroll
		for (int n = 0; n < 8; n++) {
			const int c = 8 + n, k = 2 * (c & 3) + h, nb = c >> 2;
			const uint32_t sel = nb + ((4 + nb) << 4);
			const uint32_t lo = __byte_perm(s[0][k], s[1][k], sel);
			const uint32_t hi = __byte_perm(s[2][k], s[3][k], sel);
			outq[h][n] = __byte_perm(lo, hi, 0x5410);
		}
}

/* Groestl-512 of two 64-byte messages on a lane pair; inq[h][n] = word 2n + lane, digests back in inq */
__device__ __forceinline__
void groestl512_pair_hash_64(uint32_t (&inq)[2][8], uint32_t *st, const uint32_t stride)
{
	const uint32_t lane = threadIdx.x & 1;
	uint32_t s[4][8];
	groestl512_pair_load64(inq, s, lane);
	groestl512_pair_compress(s, st, stride, lane);
	groestl512_pair_store(s, inq);
}

