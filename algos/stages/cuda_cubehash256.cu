		x0[1][1][1][1] = ROTATEUPWARDS7(x[0][1][1][1][1]);

		/* "add x_0jklm into x_1jklm modulo 2^32" */
		x1[0][0][0][0] = x[1][0][0][0][0] + x[0][0][0][0][0];
