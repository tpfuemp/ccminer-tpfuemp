"""Generate cuda/bc3_constants.cuh from ref/constants.hpp (BitcoinIII Core's
consensus constants, vendored by ref/vendor.py).

Emits every constant as 32-bit limbs, least significant first (the device
layout of bc3u<N>), plus the sliding-window schedules of the four fixed
exponents mix512 needs, replicating FixedExponent's constructor in uint.hpp:
  exp64  = FixedExponent<M64, 3>(E64)
  exp128 = FixedExponent<M128, 4>(E128)
  exp256 = FixedExponent<M256, 4>(E256)
  inv256 = Fermat exponent p-2 of F256, window 5 (the inverse256 substitute)

usage: python gen_constants.py   (run from anywhere; paths are relative to this file)
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "ref", "constants.hpp"), encoding="utf-8").read()

HEX = re.compile(r'(?:UInt<(\d)>|U256)::hex\("([0-9a-f]+)"\)')
DECL = re.compile(r'inline constexpr (std::array<(?:UInt<\d>|U256), \d+>|UInt<\d>|U256) (\w+) = (\{.*?\};|[^;]*;)', re.S)


def limbs(value, n):
    return [(value >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


consts = {}
for m in DECL.finditer(src):
    name, body = m.group(2), m.group(3)
    vals = []
    for h in HEX.finditer(body):
        L = int(h.group(1)) if h.group(1) else 4
        vals.append((L, int(h.group(2), 16)))
    consts[name] = (m.group(1).startswith("std::array"), vals)

for need in ["base", "round64", "round128", "round256", "final", "E64", "E128", "E256",
             "g64", "g128", "g256", "H_x", "H_y", "J_x", "J_y", "K_x", "K_y", "L_x", "L_y",
             "INVALID_POINT_x", "INVALID_POINT_y"]:
    assert need in consts, need
assert len(consts["base"][1]) == 8 and len(consts["round64"][1]) == 32
assert len(consts["round128"][1]) == 16 and len(consts["round256"][1]) == 16
assert len(consts["final"][1]) == 64


def schedule(e, bits, window):
    """FixedExponent<M, Window>(e): returns (steps[(squares, index)], tail)."""
    bit = lambda n: (e >> n) & 1
    i = bits - 1
    while i >= 0 and not bit(i):
        i -= 1
    steps, tail = [], 0
    while i >= 0:
        if not bit(i):
            tail += 1
            i -= 1
            continue
        low = i - (window - 1) if i >= window - 1 else 0
        while not bit(low):
            low += 1
        value = 0
        for j in range(i, low - 1, -1):
            value = (value << 1) | bit(j)
        steps.append((tail + (i - low + 1), value // 2))
        tail = 0
        i = low - 1
    return steps, tail


def check_schedule(e, bits, window, steps, tail):
    # Replay the chain on exponents: must reproduce e exactly.
    acc = 2 * steps[0][1] + 1
    for sq, ix in steps[1:]:
        acc = (acc << sq) + 2 * ix + 1
    acc <<= tail
    assert acc == e, "schedule replay mismatch"


out = []
w = out.append
w("// GENERATED by algos/bc3hash/gen_constants.py from ref/constants.hpp -- do not edit.")
w("// BitcoinIII Core v31.1.2 (ac3dbe8b47) BC3Mix consensus constants, 32-bit limbs LS first.")
w("#pragma once")
w("#include <stdint.h>")
w("")


def emit_array(name, n, vals):
    rows = ", ".join("{" + ", ".join("0x%08xu" % x for x in limbs(v, n)) + "}" for _, v in vals)
    w(f"__device__ __constant__ static const uint32_t BC3_{name.upper()}[{len(vals)}][{n}] = {{{rows}}};")


emit_array("base", 2, consts["base"][1])
emit_array("round64", 2, consts["round64"][1])
emit_array("round128", 4, consts["round128"][1])
emit_array("round256", 8, consts["round256"][1])
emit_array("final", 8, consts["final"][1])
w("")

# Host-side constants (pow-table bases, curve points) as plain arrays.
for name, n in [("g64", 2), ("g128", 4), ("g256", 8)]:
    v = consts[name][1][0][1]
    w(f"static const uint32_t BC3_HOST_{name.upper()}[{n}] = {{" + ", ".join("0x%08xu" % x for x in limbs(v, n)) + "};")
w("// Curve bases H, J, K, L as affine (x, y); mix512 uses curve[0..3] in this order.")
pts = []
for b in "HJKL":
    pts.append("{{" + ", ".join("0x%08xu" % x for x in limbs(consts[b + "_x"][1][0][1], 8)) + "}, {" +
               ", ".join("0x%08xu" % x for x in limbs(consts[b + "_y"][1][0][1], 8)) + "}}")
w("static const uint32_t BC3_HOST_CURVE[4][2][8] = {" + ",\n    ".join(pts) + "};")
for c in ["x", "y"]:
    v = consts["INVALID_POINT_" + c][1][0][1]
    w(f"__device__ __constant__ static const uint32_t BC3_INVALID_{c.upper()}[8] = {{" +
      ", ".join("0x%08xu" % x for x in limbs(v, 8)) + "};")
w("")

F256 = (1 << 256) - 36113
exps = [("EXP64", consts["E64"][1][0][1], 64, 3),
        ("EXP128", consts["E128"][1][0][1], 128, 4),
        ("EXP256", consts["E256"][1][0][1], 256, 4),
        ("INV256", F256 - 2, 256, 5)]
w("// Sliding-window schedules (FixedExponent): r = odd[IX[0]]; for i >= 1: square SQ[i]")
w("// times, multiply by odd[IX[i]]; then TAIL squarings. odd[k] = a^(2k+1).")
for name, e, bits, win in exps:
    steps, tail = schedule(e, bits, win)
    check_schedule(e, bits, win, steps, tail)
    nsq = sum(s for s, _ in steps[1:]) + tail
    w(f"// {name}: window {win}, {len(steps)} steps, {nsq} squarings + {len(steps) - 1} multiplies"
      f" + {1 + (1 << (win - 1)) - 1} for the odd-power table")
    w(f"#define BC3_{name}_WINDOW {win}")
    w(f"#define BC3_{name}_COUNT {len(steps)}")
    w(f"#define BC3_{name}_TAIL {tail}")
    w(f"__device__ __constant__ static const uint8_t BC3_{name}_SQ[{len(steps)}] = {{" + ", ".join(str(s) for s, _ in steps) + "};")
    w(f"__device__ __constant__ static const uint8_t BC3_{name}_IX[{len(steps)}] = {{" + ", ".join(str(i) for _, i in steps) + "};")
w("")

dst = os.path.join(here, "cuda", "bc3_constants.cuh")
os.makedirs(os.path.dirname(dst), exist_ok=True)
tmp = dst + ".tmp"
open(tmp, "w", encoding="ascii", newline="\n").write("\n".join(out) + "\n")
os.replace(tmp, dst)
print("wrote", dst)
for name, e, bits, win in exps:
    steps, tail = schedule(e, bits, win)
    print(f"  {name}: {len(steps)} steps, tail {tail}")
