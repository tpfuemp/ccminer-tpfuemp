/* homescrypt (Lumenite) known-answer vectors.
 *
 * Headers are the raw 80 serialized bytes (nonce = bytes 76..79, little-endian);
 * digests are the 32 output bytes in uint256 order (byte 31 most significant).
 * mainnet-*: Lumenite blocks 250/255/261; each digest meets its block's nBits.
 * alias-*: nonces of block 250 whose mix has exactly one aliased write pair,
 * one vector per pair, since the write order only shows when indices collide.
 * tuned8x1-*: 8 mix rounds and one FP pass, a short shape for the self-test.
 * Digests from the coin's own homescrypt_v12. */
#pragma once
#include <stdint.h>

struct homescrypt_kat_vec {
	const char *name;
	uint32_t bits;         // nBits of the block (0 = not a mainnet block)
	const uint8_t *header; // 80 raw bytes
	uint32_t nonce;        // written LE into bytes 76..79 before hashing, if override_nonce
	int override_nonce;
	uint32_t mix_rounds, fp_passes; // 65536/6 = consensus
	uint8_t digest[32];
};

